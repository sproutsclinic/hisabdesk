import { useEffect } from "react"

interface Props {
  fetchLatest: () => Promise<any>
  enabled?: boolean
}

/* =========================================================
   HOOK
   ========================================================= */

export default function useAutoLoadLatestTax({
  fetchLatest,
  enabled = true,
}: Props) {
  useEffect(() => {
    if (!enabled) return

    /* fire once on mount */
    fetchLatest()
  }, [enabled, fetchLatest])
}
