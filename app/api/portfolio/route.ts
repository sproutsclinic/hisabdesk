import { NextRequest, NextResponse } from "next/server"
import { requireUser } from "@/lib/security/guards"

import {
  getProfile,
  saveOnboardingProfile,
} from "@/lib/api/profile/profile.service"

function bad(message: string, status = 400) {
  return NextResponse.json({ error: message }, { status })
}

/* =========================================================
   GET ÃƒÆ’Ã†â€™Ãƒâ€šÃ‚Â¢ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬Ãƒâ€šÃ‚Â ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÂ¢Ã¢â‚¬Å¾Ã‚Â¢ Fetch profile
   ========================================================= */
export async function GET() {
  try {
    const user = await requireUser()

    const profile = await getProfile(user.id)

    return NextResponse.json({
      success: true,
      data: profile,
    })
  } catch (err) {
    console.error("Profile GET error:", err)
    return bad("Failed to load profile", 500)
  }
}

/* =========================================================
   PATCH ÃƒÆ’Ã†â€™Ãƒâ€šÃ‚Â¢ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬Ãƒâ€šÃ‚Â ÃƒÆ’Ã‚Â¢ÃƒÂ¢Ã¢â‚¬Å¡Ã‚Â¬ÃƒÂ¢Ã¢â‚¬Å¾Ã‚Â¢ Save onboarding profile (PFOS contract)
   ========================================================= */
export async function PATCH(req: NextRequest) {
  try {
    const user = await requireUser()

    const body = await req.json()

    await saveOnboardingProfile(user.id, {
      risk: body.risk,
      dependents: body.dependents,
      monthlyIncome: body.monthlyIncome,
      monthlyExpense: body.monthlyExpense,
      primaryGoal: body.primaryGoal,
    })

    const updated = await getProfile(user.id)

    return NextResponse.json({
      success: true,
      data: updated,
    })
  } catch (err) {
    console.error("Profile PATCH error:", err)
    return bad("Failed to update profile", 500)
  }
}
