import { supabase } from "@/lib/supabase"

/* =========================================================
   TYPES
========================================================= */

type Callback = () => void

/* =========================================================
   MAIN SUBSCRIBE
========================================================= */

export function subscribeOrgRealtime(
  orgId: string,
  onChange: Callback
) {
  /* ------------------------------------------------------
     ONE CHANNEL PER ORG
  ------------------------------------------------------ */

  const channel = supabase.channel(`org-${orgId}`)

  /* ------------------------------------------------------
     TABLE LISTENERS
  ------------------------------------------------------ */

  const tables = [
    "income",
    "expenses",
    "org_documents",
    "activity_logs",
  ]

  tables.forEach((table) => {
    channel.on(
      "postgres_changes",
      {
        event: "*",
        schema: "public",
        table,
        filter: `org_id=eq.${orgId}`,
      },
      () => {
        onChange()
      }
    )
  })

  channel.subscribe()

  /* ------------------------------------------------------
     CLEANUP
  ------------------------------------------------------ */

  return () => {
    supabase.removeChannel(channel)
  }
}

/* =========================================================
   LIGHT HOOK (optional helper)
========================================================= */

import { useEffect } from "react"

export function useOrgRealtime(
  orgId: string,
  onChange: Callback
) {
  useEffect(() => {
    if (!orgId) return

    const unsub = subscribeOrgRealtime(
      orgId,
      onChange
    )

    return unsub
  }, [orgId])
}
