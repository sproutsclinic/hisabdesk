import { getSupabaseAdmin } from "@/lib/supabase/gateway"

/* =========================================================
   TYPES
========================================================= */

type AuditInput = {
  orgId?: string | null
  userId?: string | null
  action: string
  metadata?: Record<string, any>
}

/* =========================================================
   CLIENT
========================================================= */

function getClient() {
  return createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.SUPABASE_SERVICE_ROLE_KEY!,
    { auth: { persistSession: false } }
  )
}

/* =========================================================
   MAIN LOGGER
========================================================= */

export async function auditLog({
  orgId,
  userId,
  action,
  metadata = {},
}: AuditInput) {
  try {
    const supabase = getClient()

    await supabase.from("audit_logs").insert({
      org_id: orgId || null,
      user_id: userId || null,
      action,
      metadata,
    })
  } catch (err) {
    /**
     * Never break main flow because of audit failure.
     * Logging must be non-blocking.
     */
    console.error("Audit log failed:", err)
  }
}

/* =========================================================
   SUGAR HELPERS (optional)
========================================================= */

export async function auditOrg(
  orgId: string,
  action: string,
  metadata?: Record<string, any>
) {
  return auditLog({ orgId, action, metadata })
}

export async function auditUser(
  userId: string,
  action: string,
  metadata?: Record<string, any>
) {
  return auditLog({ userId, action, metadata })
}
