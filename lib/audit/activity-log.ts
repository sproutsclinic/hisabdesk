"use server"

import { getSupabaseAdmin } from "@/lib/supabase/gateway"

/* =========================================================
   ADMIN CLIENT
========================================================= */

function getAdminClient() {
  return createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.SUPABASE_SERVICE_ROLE_KEY!,
    { auth: { persistSession: false } }
  )
}

/* =========================================================
   TYPES
========================================================= */

type ActivityInput = {
  userId?: string | null
  orgId?: string | null
  action: string
  entity?: string
  entityId?: string | number
  meta?: Record<string, any>
}

/* =========================================================
   CORE LOGGER
========================================================= */

export async function logActivity(input: ActivityInput) {
  try {
    const supabase = getAdminClient()

    await supabase.from("activity_logs").insert({
      user_id: input.userId ?? null,
      org_id: input.orgId ?? null,
      action: input.action,
      entity: input.entity ?? null,
      entity_id: input.entityId?.toString() ?? null,
      meta: input.meta ?? {},
    })
  } catch {
    /* never break business logic */
  }
}

/* =========================================================
   COMMON PRESETS (helpers)
========================================================= */

export function logLogin(userId: string) {
  return logActivity({
    userId,
    action: "login",
  })
}

export function logExpenseCreated(
  userId: string,
  expenseId: string,
  amount: number
) {
  return logActivity({
    userId,
    action: "expense_created",
    entity: "expense",
    entityId: expenseId,
    meta: { amount },
  })
}

export function logReportExport(userId: string) {
  return logActivity({
    userId,
    action: "report_exported",
  })
}

export function logAdminAction(
  adminId: string,
  action: string,
  meta?: any
) {
  return logActivity({
    userId: adminId,
    action: `admin_${action}`,
    meta,
  })
}
