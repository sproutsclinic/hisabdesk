import { cookies } from "next/headers"
import { createServerClient } from "@supabase/ssr"

/* =========================================================
   SUPABASE SERVER
========================================================= */

export async function getServerSupabase() {
  const cookieStore = await cookies()

  return createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        get(name: string) {
          return cookieStore.get(name)?.value
        },
      },
    }
  )
}

/* =========================================================
   AUTH GUARD
========================================================= */

export async function requireUser() {
  const cookieStore = await cookies()

  const uid = cookieStore.get("uid")?.value

  if (!uid) throw new Error("UNAUTHORIZED")

  return uid
}

/* =========================================================
   SAFE JSON
========================================================= */

export async function safeJson(req: Request) {
  try {
    return await req.json()
  } catch {
    throw new Error("INVALID_JSON")
  }
}

/* =========================================================
   SIMPLE RATE LIMIT (memory)
   good enough for Vercel serverless
========================================================= */

const hits = new Map<string, { count: number; time: number }>()

export function rateLimit(key: string, limit = 30, windowMs = 60_000) {
  const now = Date.now()

  const record = hits.get(key)

  if (!record || now - record.time > windowMs) {
    hits.set(key, { count: 1, time: now })
    return
  }

  if (record.count >= limit) {
    throw new Error("RATE_LIMIT")
  }

  record.count++
}
