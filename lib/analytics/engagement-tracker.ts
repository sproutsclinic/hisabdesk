/* =========================================================
   TYPES
========================================================= */

export type AnalyticsEvent = {
  event: string
  meta?: Record<string, any>
}

/* =========================================================
   CORE TRACK (CLIENT SAFE)
========================================================= */

export async function trackEvent(
  supabase: any,
  userId: string | null,
  input: AnalyticsEvent
) {
  try {
    await supabase.from("analytics_events").insert({
      user_id: userId,
      event: input.event,
      meta: input.meta || {},
    })
  } catch {
    /* never break app */
  }
}

