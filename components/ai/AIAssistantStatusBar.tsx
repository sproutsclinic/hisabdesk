import { useAIUsage } from "@/lib/hooks/useAIUsage"

// ==========================================================
// HELPERS
// ==========================================================

function bg(status: string) {
  if (status === "healthy") return "bg-green-50 border-green-200"
  if (status === "warning") return "bg-yellow-50 border-yellow-200"
  return "bg-red-50 border-red-200"
}

function text(status: string) {
  if (status === "healthy") return "text-green-700"
  if (status === "warning") return "text-yellow-700"
  return "text-red-700"
}

// ==========================================================
// COMPONENT
// ==========================================================

export default function AIAssistantStatusBar() {
  const { data, loading } = useAIUsage()

  if (loading || !data) return null

  const { summary } = data

  return (
    <div
      className={`
        w-full border rounded-lg
        px-3 py-2 text-xs
        flex items-center justify-between
        ${bg(summary.status)}
      `}
    >
      {/* Left */}
      <div className={`font-medium ${text(summary.status)}`}>
        AI Budget Status: {summary.status.toUpperCase()}
      </div>

      {/* Right */}
      <div className="flex gap-4 text-muted-foreground">
        <span>Cost: ${summary.totalCost}</span>
        <span>Remaining: ${summary.remainingBudget}</span>
        <span>Tokens: {summary.totalTokens}</span>
      </div>
    </div>
  )
}
