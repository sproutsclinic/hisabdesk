import { ReactNode, useState } from "react"
import UpgradeModal from "@/components/billing/upgrade-modal"

/* =========================================================
   COMPONENT
========================================================= */

export default function PaywallButton({
  isPro,
  onClick,
  feature,
  children,
  className = "",
}: {
  isPro: boolean
  onClick?: () => void
  feature?: string
  children: ReactNode
  className?: string
}) {
  const [open, setOpen] = useState(false)

  function handle() {
    if (isPro) {
      onClick?.()
      return
    }

    setOpen(true)
  }

  /* ======================================================
     UI
  ====================================================== */

  return (
    <>
      <button
        onClick={handle}
        className={className}
      >
        {children}
      </button>

      <UpgradeModal
        open={open}
        onClose={() => setOpen(false)}
        feature={feature}
      />
    </>
  )
}
